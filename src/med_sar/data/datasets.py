from __future__ import annotations

import json
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from torch.utils.data import Dataset

from med_sar.data.augment import (
    CorruptionConfig,
    build_default_config,
    make_negative,
    normalize_all,
)


def _read_jsonl(
    path: str | Path, max_items: Optional[int] = None
) -> List[Dict[str, Any]]:
    path = Path(path)
    data: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for i, line in enumerate(f):
            if not line.strip():
                continue
            data.append(json.loads(line))
            if max_items is not None and len(data) >= max_items:
                break
    return data


@dataclass(frozen=True)
class CriticDatasetConfig:
    # Sampling mix
    p_real: float = 0.7
    p_corrupt: float = 0.3
    p_gneg: float = 0.0  # optional, later

    # Determinism
    seed: int = 0

    # Corruption behavior (weak negatives)
    corrupt_num_transforms: Tuple[int, int] = (1, 3)
    corrupt_seed_offset: int = 10_000

    # Normalization behavior (passed through normalize_all in augment.py)
    # If you want to adjust header masking probability, do it inside augment.normalize_all()

    # Dataset sizing
    # "epoch_size" controls how many samples __len__ reports.
    # If None, defaults to len(mimic_chunks).
    epoch_size: Optional[int] = None

    # Optional: truncate samples for C (helps length cheating & stabilizes batches)
    max_chars: Optional[int] = None


class CriticDataset(Dataset):
    """
    Warm-up + main training dataset for Critic/Discriminator C.

    It yields items like:
      {
        "text": <normalized text>,
        "label": 1 or 0,   # 1=real, 0=fake
        "kind": "real" | "corrupt" | "gneg",
        "meta": {...}      # passthrough identifiers
      }

    Expected input jsonl format for mimic chunks:
      {"id": "...", "text": "...", "meta": {...}}

    Optional g_neg jsonl format (generated by G):
      {"id": "...", "text": "...", "meta": {...}}   # label will be 0
    """

    def __init__(
        self,
        mimic_chunks_path: str | Path,
        cfg: CriticDatasetConfig,
        gneg_path: Optional[str | Path] = None,
        max_mimic_items: Optional[int] = None,
        max_gneg_items: Optional[int] = None,
    ):
        super().__init__()
        self.cfg = cfg

        self.mimic: List[Dict[str, Any]] = _read_jsonl(
            mimic_chunks_path, max_items=max_mimic_items
        )
        if not self.mimic:
            raise ValueError(f"No records loaded from {mimic_chunks_path}")

        self.gneg: List[Dict[str, Any]] = []
        if gneg_path is not None:
            self.gneg = _read_jsonl(gneg_path, max_items=max_gneg_items)

        # validate probabilities
        if not (
            0.0 <= cfg.p_real <= 1.0
            and 0.0 <= cfg.p_corrupt <= 1.0
            and 0.0 <= cfg.p_gneg <= 1.0
        ):
            raise ValueError("Probabilities must be in [0,1].")
        s = cfg.p_real + cfg.p_corrupt + cfg.p_gneg
        if abs(s - 1.0) > 1e-6:
            raise ValueError(f"p_real + p_corrupt + p_gneg must sum to 1.0, got {s}")

        if cfg.p_gneg > 0.0 and not self.gneg:
            raise ValueError("p_gneg > 0 but gneg_path provided no samples.")

        # corruption config (you can override weights in build_default_config if desired)
        base_corrupt_cfg = build_default_config(seed=cfg.seed + cfg.corrupt_seed_offset)
        self.corrupt_cfg = CorruptionConfig(
            seed=base_corrupt_cfg.seed,
            num_transforms=cfg.corrupt_num_transforms,
            transform_weights=base_corrupt_cfg.transform_weights,
        )

        self._epoch_size = cfg.epoch_size or len(self.mimic)

    def __len__(self) -> int:
        return self._epoch_size

    def _rng_for_index(self, idx: int) -> random.Random:
        # Deterministic RNG per index for reproducibility across workers.
        # idx is enough if seed is fixed.
        return random.Random(self.cfg.seed * 1_000_003 + idx)

    def _truncate(self, text: str) -> str:
        if self.cfg.max_chars is None:
            return text
        return text[: self.cfg.max_chars]

    def _pick_mimic_record(self, rng: random.Random) -> Dict[str, Any]:
        j = rng.randrange(len(self.mimic))
        return self.mimic[j]

    def _pick_gneg_record(self, rng: random.Random) -> Dict[str, Any]:
        j = rng.randrange(len(self.gneg))
        return self.gneg[j]

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        rng = self._rng_for_index(idx)

        u = rng.random()
        if u < self.cfg.p_real:
            rec = self._pick_mimic_record(rng)
            text = rec.get("text", "")
            text = self._truncate(text)
            # normalize_all does PHI masking + whitespace + partial header masking (per your augment.py)
            text = normalize_all(text, rng=rng)
            return {
                "text": text,
                "label": 1,
                "kind": "real",
                "meta": rec.get("meta", {}) | {"id": rec.get("id")},
            }

        u -= self.cfg.p_real
        if u < self.cfg.p_corrupt:
            rec = self._pick_mimic_record(rng)
            text = rec.get("text", "")
            text = self._truncate(text)
            # make_negative internally normalize_all first (recommended pattern)
            # ensure determinism by setting corrupt_cfg.seed per-sample
            corrupt_cfg = CorruptionConfig(
                seed=(self.cfg.seed * 1_000_003 + idx + self.cfg.corrupt_seed_offset),
                num_transforms=self.corrupt_cfg.num_transforms,
                transform_weights=self.corrupt_cfg.transform_weights,
            )
            neg = make_negative(text, cfg=corrupt_cfg)
            return {
                "text": neg,
                "label": 0,
                "kind": "corrupt",
                "meta": rec.get("meta", {}) | {"id": rec.get("id")},
            }

        # gneg (optional)
        rec = self._pick_gneg_record(rng)
        text = rec.get("text", "")
        text = self._truncate(text)
        text = normalize_all(text, rng=rng)
        return {
            "text": text,
            "label": 0,
            "kind": "gneg",
            "meta": rec.get("meta", {}) | {"id": rec.get("id")},
        }
